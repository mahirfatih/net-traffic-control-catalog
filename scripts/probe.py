#!/usr/bin/env python3
"""Optional: ask an external service what a host *is*, and cache the answer.

    python3 scripts/probe.py                       # probe the hosts needing review
    python3 scripts/probe.py --host plex.tv

This script does **not** decide a category. It collects evidence — is the host
live, does anyone else recognise it, and under what label — and writes it to
`evidence/`. A person still reads the evidence and adds the rule.

Why it exists: a host with no rule is not a host with a known category. It is
an open question, and `docs/NEEDS-REVIEW.md` is where those questions are kept
visible. This is how you answer one without guessing.

## Keys

Both are optional; with neither set the script explains what is missing and
exits 0, because a missing key is a normal state, not an error.

- `VIRUSTOTAL_API_KEY` — see the note below before using it.
- `UMBRELLA_API_KEY` — Cisco Umbrella Investigate.

## A note on VirusTotal

Its **Public** API states it must not be used in commercial products or
services. This catalog ships inside a commercial app, so a free VT key is not
usable here and `sources.json` records that verdict. If you hold a VT Premium
agreement that permits your use, the licence reason does not apply — but the
registry still has to say so, in writing, before anything is fetched. Edit
`sources.json`, do not edit this file.

## A note on Umbrella

Cisco announced the end of sale of Umbrella SIG / DNS on 1 September 2026.
Evidence gathered through it is worth having while it exists; it is not
something to build a permanent pipeline on.

Answers are cached in `evidence/probes.json` and never re-fetched, so a repeat
run costs nothing and the evidence a rule was written from stays readable
after the service is gone.
"""
import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from datetime import date

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sources as source_registry  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EVIDENCE = os.path.join(ROOT, "evidence")
CACHE = os.path.join(EVIDENCE, "probes.json")
TIMEOUT = 20

UA = "net-traffic-control-catalog/1.0 (catalog probe)"


def load_cache():
    if os.path.exists(CACHE):
        try:
            with open(CACHE, encoding="utf-8") as handle:
                return json.load(handle)
        except ValueError:
            pass
    return {}


def save_cache(cache):
    os.makedirs(EVIDENCE, exist_ok=True)
    with open(CACHE, "w", encoding="utf-8") as handle:
        json.dump(cache, handle, ensure_ascii=False, indent=2, sort_keys=True)
        handle.write("\n")


def get(url, headers):
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=TIMEOUT) as response:
        return json.loads(response.read().decode("utf-8", "replace"))


def probe_virustotal(host, key):
    data = get(
        f"https://www.virustotal.com/api/v3/domains/{host}",
        {"x-apikey": key, "Accept": "application/json", "User-Agent": UA},
    )
    attributes = (data.get("data") or {}).get("attributes") or {}
    return {
        "categories": attributes.get("categories") or [],
        "popularity_rank": attributes.get("popularity_rank"),
        "last_analysis_stats": attributes.get("last_analysis_stats") or {},
    }


def probe_umbrella(host, key):
    data = get(
        f"https://investigate.api.umbrella.com/domains/categorization/{host}",
        {"Authorization": f"Bearer {key}", "User-Agent": UA},
    )
    return {
        "categories": data.get("categories") or [],
        "risk_score": ((data.get("found") or {}).get("risk_score")),
    }


def permitted(provider):
    """Has the registry recorded that this provider may be used here?"""
    registry = source_registry.load()
    for source in registry.get("sources", []):
        if source.get("provider") == provider:
            return source_registry.verdict(source)
    return False, f"no record in sources.json for provider {provider!r}"


def main(argv):
    parser = argparse.ArgumentParser(description="Probe hosts for evidence. Decides nothing.")
    parser.add_argument("--host", action="append", default=[], help="host to probe; repeatable")
    args = parser.parse_args(argv[1:])

    providers = []
    if os.environ.get("VIRUSTOTAL_API_KEY"):
        providers.append(("virustotal", os.environ["VIRUSTOTAL_API_KEY"], probe_virustotal))
    if os.environ.get("UMBRELLA_API_KEY"):
        providers.append(("umbrella", os.environ["UMBRELLA_API_KEY"], probe_umbrella))

    if not providers:
        print("No API key set — nothing to do.")
        print("  export UMBRELLA_API_KEY=...        (Investigate; free tier is rate limited)")
        print("  export VIRUSTOTAL_API_KEY=...      (see the licence note at the top of this file)")
        print("\nEvidence is optional. A host can be categorised from its rules.json entry alone;")
        print("this only makes the answer checkable instead of guessed.")
        return 0

    usable = []
    for provider, key, function in providers:
        ok, reason = permitted(provider)
        if ok:
            usable.append((provider, key, function))
        else:
            print(f"· skipping {provider}: {reason}", file=sys.stderr)

    if not usable:
        print("every configured provider is blocked by sources.json", file=sys.stderr)
        return 1

    if args.host:
        hosts = args.host
    else:
        summary_path = os.path.join(EVIDENCE, "harvest-summary.json")
        if not os.path.exists(summary_path):
            print(f"nothing to probe: {summary_path} not found (run harvest.py first)", file=sys.stderr)
            return 1
        with open(summary_path, encoding="utf-8") as handle:
            hosts = json.load(handle).get("needs_review") or []

    if not hosts:
        print("no hosts need review")
        return 0

    cache = load_cache()
    print(f"probing {len(hosts)} host(s) against {', '.join(p for p, _, _ in usable)}\n")

    for host in hosts:
        entry = cache.setdefault(host, {})
        for provider, key, function in usable:
            if provider in entry:
                continue
            try:
                entry[provider] = function(host, key)
                print(f"  {host:40} {provider}: {entry[provider]}")
            except urllib.error.HTTPError as error:
                entry[provider] = {"error": f"HTTP {error.code}"}
                print(f"  {host:40} {provider}: HTTP {error.code}")
            except Exception as error:  # noqa: BLE001 - one bad host must not stop the run
                entry[provider] = {"error": str(error)}
                print(f"  {host:40} {provider}: {error}")

    cache["_generated"] = date.today().isoformat()
    save_cache(cache)
    print(f"\n✓ evidence/{os.path.basename(CACHE)}")
    print("  This decided nothing. Read it, then add a rule to rules.json or a")
    print("  line to docs/NEEDS-REVIEW.md saying why.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))