#!/usr/bin/env python3
"""Build docs/reference/COVERAGE.md — how much of the catalog is measured, and from where.

    python3 scripts/catalog/build-coverage.py
    python3 scripts/catalog/build-coverage.py --check

`docs/reference/CATALOG.md` says how big the catalog is. This page answers the questions a
size does not: which category the sample leans on, how much of each category the
page-text analysis could actually read, and whether one source is carrying a
category on its own. A catalog that is 53% `finance` from a single bank list is a
fact worth writing once, in a generated file, rather than rediscovering per audit.

Generated from `catalog.json`, `rules.json`, `seeds/categories.json`,
`evidence/harvest-summary.json` and `docs/analysis/out/matrix-data.json`. Do not
edit it by hand; `--check` reports when the committed file is stale.
"""
import argparse
from collections import Counter, defaultdict
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CATALOG = os.path.join(ROOT, "catalog.json")
RULES = os.path.join(ROOT, "config/rules.json")
CATEGORIES = os.path.join(ROOT, "seeds", "categories.json")
SUMMARY = os.path.join(ROOT, "evidence", "harvest-summary.json")
MATRIX = os.path.join(ROOT, "docs", "analysis", "out", "matrix-data.json")
OUT = os.path.join(ROOT, "docs", "reference", "COVERAGE.md")

# A category that gets more than this share of its rows from one harvest source
# inherits that source's blind spots wholesale. The threshold is a warning, not a
# failure: a founding list legitimately owns a category on day one, and the point
# is to name that out loud rather than to forbid it.
CONCENTRATION_WARN = 0.40

# Concentrations that are known and accepted, so the warning above stays about
# *new* single-source dependencies. Keyed (category, source).
EXPECTED_CONCENTRATION = {
    ("finance", "adguard-https-exclusions-banks"): "the founding bank list",
}


def load_json(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def service_covered(host, service_domains):
    """True when a service already names this host (whole or as a subdomain)."""
    if host in service_domains:
        return True
    return any(host.endswith("." + domain) for domain in service_domains)


def source_contributions(categories, summary):
    """Per category: how many imported rows each harvest source supplied.

    Only rows whose host is *in the catalog under that category* count — a
    harvested row that was later dropped is not part of the category any more.
    """
    contributions = defaultdict(Counter)
    for row in summary.get("categorized", []):
        host = row.get("host")
        if categories.get(host) == row.get("category"):
            contributions[row["category"]][row["source"]] += 1
    return contributions


def ambiguity_rate(predictions):
    """Share of measured hosts where the model's top two are within 10 points.

    A margin that small is the model declining to choose, so it belongs in the
    coverage story next to balanced accuracy rather than hidden in a per-host
    table.
    """
    if not predictions:
        return None, 0
    torn = 0
    for pred in predictions:
        top = pred.get("top_predictions") or []
        if len(top) >= 2 and (top[0]["probability"] - top[1]["probability"]) < 0.10:
            torn += 1
    return torn / len(predictions), torn


def build(catalog, rules, categories, summary, matrix):
    lines = []
    add = lines.append

    hosts = catalog["categories"]
    total = len(hosts)
    counts = Counter(hosts.values())
    classes = sorted(counts)

    add("# Coverage and quality")
    add("")
    add("Generated by `scripts/catalog/build-coverage.py`. **Do not edit by hand** —")
    add("it is rebuilt from the catalog, the rules and the analysis output. It answers")
    add("the questions the catalog's [size](CATALOG.md) does not: which category the")
    add("sample leans on, how much of each category was read, and whether one source")
    add("carries a category alone.")
    add("")

    # --- Size and skew ---
    add("## Size and skew")
    add("")
    add(f"**{total:,} names** across **{len(classes)} categories**, plus "
        f"**{len(catalog.get('services', []))} services**.")
    add("")
    finance = counts.get("finance", 0)
    government = counts.get("government", 0)
    add(f"The two largest categories are `finance` ({finance:,}, {finance / total:.0%})")
    add(f"and `government` ({government:,}, {government / total:.0%}) — together")
    add(f"**{(finance + government) / total:.0%}** of the catalog. This is the single")
    add("most important fact about the data: a page-text model trained on it learns")
    add("the majority class first, which is why accuracy (89%) and balanced accuracy")
    add("(61%) disagree — see [`docs/analysis/README.md`](../analysis/README.md).")
    add("")
    add("| Category | Hosts | Share |")
    add("| :--- | --: | --: |")
    for name, count in counts.most_common(12):
        add(f"| `{name}` | {count:,} | {count / total:.1%} |")
    rest = len(classes) - 12
    if rest > 0:
        tail = total - sum(count for _, count in counts.most_common(12))
        add(f"| _{rest} more_ | {tail:,} | {tail / total:.1%} |")
    add("")

    # --- Source concentration ---
    add("## Source concentration")
    add("")
    add("How much of each category comes from a single harvest source. A category")
    add(f"that leans on one list inherits that list's blind spots. Above "
        f"{CONCENTRATION_WARN:.0%} is flagged.")
    add("")
    contributions = source_contributions(categories, summary)
    concentrated = []
    for name, count in counts.items():
        top = contributions.get(name, Counter()).most_common(1)
        if top and top[0][1] / count > CONCENTRATION_WARN:
            concentrated.append((name, top[0][0], top[0][1]))
    if concentrated:
        add("| Category | Hosts | Top source | Share | Note |")
        add("| :--- | --: | :--- | --: | :--- |")
        for name, src, count in sorted(concentrated, key=lambda t: -t[2] / counts[t[0]]):
            share = count / counts[name]
            expected = EXPECTED_CONCENTRATION.get((name, src))
            note = f"known: {expected}" if expected else "**single-source dependency**"
            add(f"| `{name}` | {counts[name]:,} | `{src}` | {share:.0%} | {note} |")
        add("")
    else:
        add("No category takes more than "
            f"{CONCENTRATION_WARN:.0%} of its rows from one harvest source.")
        add("")

    # --- Measured coverage ---
    add("## Measured coverage")
    add("")
    if matrix and matrix.get("coverage"):
        coverage = matrix["coverage"]
        measured_total = sum(row["measured"] for row in coverage.values())
        add("The page-text analysis reads a host's homepage. Not every host has a")
        add("readable one — many bank pages are a login form or a JS shell. This is how")
        add("much of each category it could actually measure.")
        add("")
        add(f"**{measured_total:,} of {total:,} hosts measured ({measured_total / total:.0%})**")
        add("")
        add("| Category | In catalog | Measured | Coverage |")
        add("| :--- | --: | --: | --: |")
        for name in sorted(coverage, key=lambda c: coverage[c]["measured"] / max(coverage[c]["in_catalog"], 1)):
            row = coverage[name]
            add(f"| `{name}` | {row['in_catalog']:,} | {row['measured']:,} | "
                f"{row['measured'] / max(row['in_catalog'], 1):.0%} |")
        add("")
    else:
        add("_No analysis output present — run `scripts/analysis/build-matrix.py` to")
        add("populate this section._")
        add("")

    # --- Quality metrics ---
    add("## Quality metrics")
    add("")
    service_domains = {d for service in catalog.get("services", []) for d in service["domains"]}
    covered = sum(1 for host in hosts if service_covered(host, service_domains))
    overrides = rules.get("drop", {}).get("override", {}) or {}
    rows = [("Names in the catalog", f"{total:,}", "the whole data file"),
            ("Names a service also names", f"{covered:,} ({covered / total:.0%})",
             "whole host or subdomain of a service domain"),
            ("Human overrides", f"{len(overrides):,}",
             "rows relabelled by hand in `rules.json → drop.override`")]
    if matrix:
        macro = matrix.get("macro_avg", {})
        weighted = matrix.get("weighted_avg", {})
        rate, torn = ambiguity_rate(matrix.get("predictions"))
        rows += [
            ("Accuracy", f"{matrix.get('accuracy', 0):.0%}",
             "correct on the measured sample, majority-class weighted"),
            ("Balanced accuracy", f"{matrix.get('balanced_accuracy', 0):.0%}",
             "correct per class, averaged — the honest headline"),
        ]
        leakage = matrix.get("leakage") or {}
        if leakage:
            rows.append(("Grouped balanced accuracy", f"{leakage.get('balanced_accuracy', 0):.0%}",
                         "balanced accuracy with a host's owner held out of its fold "
                         f"({leakage.get('grouping', 'owner')}); the gap is owner leakage"))
        rows += [
            ("Macro F1", f"{macro.get('f1-score', 0):.2f}",
             "unweighted mean F1 across classes"),
            ("Weighted F1", f"{weighted.get('f1-score', 0):.2f}",
             "F1 weighted by class size"),
        ]
        if rate is not None:
            rows.append(("Ambiguous predictions", f"{rate:.0%} ({torn:,})",
                         "measured hosts whose top two categories are within 10 points"))
    add("| Metric | Value | Meaning |")
    add("| :--- | :--- | :--- |")
    for name, value, meaning in rows:
        add(f"| {name} | {value} | {meaning} |")
    add("")
    add("The full analysis, and what each score does and does not cover, is in")
    add("[`docs/analysis/README.md`](../analysis/README.md). The licensing and the shape")
    add("of each source is in [`docs/reference/SOURCES.md`](SOURCES.md).")
    add("")

    return "\n".join(lines)


def main(argv):
    parser = argparse.ArgumentParser(description="Build or check docs/reference/COVERAGE.md.")
    parser.add_argument("--check", action="store_true",
                        help="verify the committed file is current; write nothing")
    args = parser.parse_args(argv[1:])

    catalog = load_json(CATALOG)
    rules = load_json(RULES)
    categories = load_json(CATEGORIES)
    summary = load_json(SUMMARY) if os.path.exists(SUMMARY) else {}
    matrix = load_json(MATRIX) if os.path.exists(MATRIX) else None

    rendered = build(catalog, rules, categories, summary, matrix)

    if args.check:
        if not os.path.exists(OUT):
            print(f"✗ {os.path.relpath(OUT, ROOT)} is missing — run build-coverage.py",
                  file=sys.stderr)
            return 1
        with open(OUT, encoding="utf-8") as handle:
            committed = handle.read()
        if committed.rstrip("\n") != rendered.rstrip("\n"):
            print(f"✗ {os.path.relpath(OUT, ROOT)} is stale — run build-coverage.py",
                  file=sys.stderr)
            return 1
        print(f"✓ {os.path.relpath(OUT, ROOT)} is current")
        return 0

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(rendered + "\n")
    print(f"Saved {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
